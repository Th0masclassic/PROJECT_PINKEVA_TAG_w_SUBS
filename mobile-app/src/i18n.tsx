export const TRANSLATIONS: Readonly<Record<Language, Dictionary>> = Object.freeze({
  en,
  pt,
  fr,
  de,
  zh,
  it,
  es,
});

const languageCodeSet: ReadonlySet<string> = new Set(LANGUAGE_CODES);
const interpolationPattern = /\{\{\s*([a-zA-Z][\w]*)\s*\}\}/g;

export function isLanguage(value: unknown): value is Language {
  return typeof value === 'string' && languageCodeSet.has(value);
}

export function normalizeLanguage(value: unknown, fallback: Language = 'en'): Language {
  return isLanguage(value) ? value : fallback;
}

export function getLanguageOption(language: unknown): LanguageOption {
  const validLanguage = normalizeLanguage(language);
  return LANGUAGES.find((option) => option.code === validLanguage) ?? LANGUAGES[0]!;
}

function templateVariables(template: string): string[] {
  const variables = new Set<string>();
  for (const match of template.matchAll(interpolationPattern)) {
    const variable = match[1];
    if (variable) variables.add(variable);
  }
  return [...variables].sort();
}

/**
 * Checks dictionary completeness and interpolation compatibility at runtime.
 * This is useful for JavaScript consumers and catches malformed generated bundles
 * even though the dictionaries are also checked statically by TypeScript.
 */
export function validateTranslations(): void {
  const expectedKeys = Object.keys(en).sort() as TranslationKey[];

  for (const language of LANGUAGE_CODES) {
    const dictionary = TRANSLATIONS[language] as Record<string, string>;
    const actualKeys = Object.keys(dictionary).sort();
    const missing = expectedKeys.filter((key) => !(key in dictionary));
    const extra = actualKeys.filter((key) => !(key in en));

    if (missing.length || extra.length) {
      throw new Error(
        `Invalid ${language} translations. Missing: ${missing.join(', ') || 'none'}; extra: ${extra.join(', ') || 'none'}.`,
      );
    }

    for (const key of expectedKeys) {
      const expectedVariables = templateVariables(en[key]);
      const actualVariables = templateVariables(dictionary[key] ?? '');
      if (expectedVariables.join('|') !== actualVariables.join('|')) {
        throw new Error(
          `Invalid interpolation variables for ${language}.${key}. Expected ${expectedVariables.join(', ') || 'none'}; received ${actualVariables.join(', ') || 'none'}.`,
        );
      }
    }
  }
}

validateTranslations();

export function translate(
  language: unknown,
  key: TranslationKey,
  params: TranslationParams = {},
): string {
  const validLanguage = normalizeLanguage(language);
  const template = TRANSLATIONS[validLanguage][key] ?? en[key];

  return template.replace(interpolationPattern, (token, variable: string) => {
    const value = params[variable];
    return value === undefined || value === null ? token : String(value);
  });
}

export type Translate = (key: TranslationKey, params?: TranslationParams) => string;

export function formatRelativeTime(t: Translate, value: string): string {
  if (value === 'Just now') return t('time.justNow');

  const minutes = /^(\d+)\s*min/.exec(value);
  if (minutes?.[1]) return t('time.minutesAgo', { count: Number(minutes[1]) });

  const hours = /^(\d+)\s*h/.exec(value);
  if (hours?.[1]) return t('time.hoursAgo', { count: Number(hours[1]) });

  return value;
}

